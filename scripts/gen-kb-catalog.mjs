/**
 * Generate docs/kb-catalog.md from packages/kb/content.
 *
 * Every item, its window, its sources and its review date, in one place a human
 * can scan — which is what a clinical reviewer needs and what nobody will
 * maintain by hand.
 *
 * Reads the YAML rather than importing the zod schema, so `pnpm docs:gen` has no
 * TypeScript build step. `pnpm kb:validate` is what enforces the schema; this
 * only renders what is there.
 */

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { load } from 'js-yaml';

const CONTENT = 'packages/kb/content';

/** LMP day offset -> "36+0" the way clinicians write it. */
function asGestation(days) {
  if (days < 0) return `${days}d`;
  return `${Math.floor(days / 7)}+${days % 7}`;
}

function windowLabel(item) {
  if (item.kind !== 'schedule' || !item.window) return '—';
  const { anchor, start_days: a, end_days: b } = item.window;
  if (anchor === 'LMP') return `${asGestation(a)} → ${asGestation(b)}`;
  return `${anchor} ${a >= 0 ? '+' : ''}${a}d → ${b >= 0 ? '+' : ''}${b}d`;
}

function yamlFiles(dir) {
  if (!existsSyncSafe(dir)) return [];
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...yamlFiles(full));
    else if (entry.endsWith('.yaml') || entry.endsWith('.yml')) out.push(full);
  }
  return out.sort();
}

function existsSyncSafe(p) {
  try {
    statSync(p);
    return true;
  } catch {
    return false;
  }
}

export function readItems(contentDir = CONTENT) {
  const items = [];
  for (const file of yamlFiles(contentDir)) {
    const doc = load(readFileSync(file, 'utf8'));
    for (const item of doc?.items ?? []) {
      items.push({ ...item, _file: relative('packages/kb', file) });
    }
  }
  return items;
}

export function renderCatalog(items, today = new Date().toISOString().slice(0, 10)) {
  const lines = [];
  lines.push('# KB catalogue');
  lines.push('');
  lines.push(
    '<!-- Generated by `pnpm docs:gen` from packages/kb/content. Do not edit by hand. -->',
  );
  lines.push('');
  if (items.length === 0) {
    lines.push('No KB items yet. The first ones arrive at roadmap step 3.');
    lines.push('');
    return lines.join('\n');
  }

  const published = items.filter((i) => (i.status ?? 'published') === 'published');
  const drafts = items.filter((i) => i.status === 'draft');
  const overdue = items.filter((i) => i.review_by && i.review_by < today);

  lines.push(
    `${items.length} item(s): ${published.length} published, ${drafts.length} draft. ` +
      `Windows are shown as gestational age (weeks+days) from LMP where that is the anchor.`,
  );
  lines.push('');
  if (drafts.length > 0) {
    lines.push(
      `**${drafts.length} draft item(s)** do not publish and generate no task: ` +
        `${drafts.map((d) => `\`${d.id}\``).join(', ')}. A draft is the correct outcome ` +
        'when the source is unclear.',
    );
    lines.push('');
  }
  if (overdue.length > 0) {
    lines.push(
      `**${overdue.length} item(s) are past their review date** and must be rechecked ` +
        `against their source: ${overdue.map((d) => `\`${d.id}\``).join(', ')}.`,
    );
    lines.push('');
  }

  const phases = [...new Set(items.map((i) => i.phase))].sort();
  for (const phase of phases) {
    lines.push(`## ${phase}`);
    lines.push('');
    lines.push(
      '| id | Hebrew | English | Window | Coverage | Priority | Review by | Sources |',
    );
    lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const item of items
      .filter((i) => i.phase === phase)
      .sort((a, b) => a.id.localeCompare(b.id))) {
      const he = item.locales?.he?.title ?? '—';
      const en = item.locales?.en?.title ?? '—';
      const srcs = (item.sources ?? []).map((u, n) => `[${n + 1}](${u})`).join(' ');
      const draft = item.status === 'draft' ? ' *(draft)*' : '';
      lines.push(
        `| \`${item.id}\`${draft} | ${he} | ${en} | ${windowLabel(item)} | ` +
          `${item.coverage ?? '—'} | ${item.priority ?? '—'} | ${item.review_by ?? '—'} | ${srcs || '—'} |`,
      );
    }
    lines.push('');
  }

  return lines.join('\n');
}

export function generateCatalog(contentDir = CONTENT) {
  const items = readItems(contentDir);
  return { markdown: renderCatalog(items), count: items.length };
}
